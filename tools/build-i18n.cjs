// Build both runtimes from one reviewed catalogue. No runtime dependencies.
const fs=require('node:fs'),path=require('node:path')
const root=path.resolve(__dirname,'..')
function build(){
  const messages={}
  for(const line of fs.readFileSync(path.join(__dirname,'i18n/en.tsv'),'utf8').split(/\r?\n/)){
    if(!line||line.startsWith('#'))continue
    const tab=line.indexOf('\t')
    if(tab<1)throw new Error('Missing translation: '+line)
    const key=line.slice(0,tab),value=line.slice(tab+1).replace(/\\s/g,' ')
    if(messages[key]&&messages[key]!==value)throw new Error('Conflicting translation: '+key)
    messages[key]=value
  }
  const titles={}
  for(const route of JSON.parse(fs.readFileSync(path.join(root,'app.json'),'utf8')).pages){
    const json=JSON.parse(fs.readFileSync(path.join(root,route+'.json'),'utf8'))
    titles[route]=json.navigationBarTitleText||'AI 控糖助手'
  }
  const engine=fs.readFileSync(path.join(__dirname,'i18n/runtime.txt'),'utf8')
  const header='// Generated by node tools/build-i18n.cjs. Edit tools/i18n instead.\nvar messages = '+JSON.stringify(messages)+';\n'
  const outputs={
    'utils/locales/en.js':header+'var pattern = RegExp;\n'+engine+'\nmodule.exports = { t: t, tag: tag, list: list, content: content, name: name, messages: messages, titles: '+JSON.stringify(titles,null,2)+' };\n',
    'utils/i18n.wxs':header+'var pattern = getRegExp;\n'+engine+'\nmodule.exports = { t: t, tag: tag, list: list, content: content, name: name };\n'
  }
  return outputs
}
if(require.main===module){
  for(const [name,text] of Object.entries(build())){
    const file=path.join(root,name)
    fs.mkdirSync(path.dirname(file),{recursive:true})
    fs.writeFileSync(file,text)
  }
}
module.exports={build}
